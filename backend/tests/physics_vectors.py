"""Writes `shared/physics-test-vectors.json`: inputs and the outputs of
`app/analysis/physics.py`, which `test_physics.py` and the frontend's
`physics.test.ts` both check. That keeps the Python and TypeScript copies
from drifting apart; the physics itself is hand-checked in `test_physics.py`.

Regenerate after a deliberate change to the model (from `backend/`):
    python -m tests.physics_vectors
"""

import json
from dataclasses import asdict
from pathlib import Path

from app.analysis import physics

VECTORS_PATH = Path(__file__).resolve().parents[2] / "shared" / "physics-test-vectors.json"

_RHO = physics.air_density(20, humidity_pct=50)
SETUPS = {
    "pursuiter": physics.Setup(mass_kg=83, cda_m2=0.20, rho=_RHO),
    "sprinter": physics.Setup(mass_kg=95, cda_m2=0.26, rho=_RHO, crr=0.003, efficiency=0.975, rotating_mass_kg=1.5),
    "junior": physics.Setup(mass_kg=62, cda_m2=0.24, rho=1.15, crr=0.004, efficiency=0.97, rotating_mass_kg=1.0),
}

AIR = [
    {"temp_c": 15, "pressure_pa": None, "elevation_m": 0, "humidity_pct": 0},
    {"temp_c": 20, "pressure_pa": None, "elevation_m": 0, "humidity_pct": 50},
    {"temp_c": 26, "pressure_pa": 98_200, "elevation_m": 0, "humidity_pct": 40},
    {"temp_c": 28, "pressure_pa": None, "elevation_m": 1_850, "humidity_pct": 30},
    {"temp_c": -5, "pressure_pa": None, "elevation_m": 200, "humidity_pct": 80},
]
SPEEDS = [(name, v, a) for name in SETUPS for v, a in ((0, 0), (8.5, 0), (15, 0), (12, 0.8), (16, -0.3))]
POWERS = [(name, p) for name in SETUPS for p in (0, 50, 300, 450, 1200)]
SIMULATIONS = [
    {"setup": "pursuiter", "distance_m": 4000, "power_w": 450, "standing": True, "split_every_m": 125},
    {"setup": "pursuiter", "distance_m": 4000, "power_w": 450, "standing": False, "split_every_m": 250},
    {"setup": "sprinter", "distance_m": 1000, "power_w": 600, "standing": True, "split_every_m": 250},
    {"setup": "sprinter", "distance_m": 200, "power_w": 1100, "standing": False},
    {"setup": "junior", "distance_m": 2000, "power_w": 280, "standing": True, "split_every_m": 333.33},
    {
        "setup": "junior",
        "distance_m": 500,
        "power_w": 500,
        "standing": True,
        "split_every_m": 125,
        "start_power_ratio": 1,
        "start_force_n": 180,
    },
]
TARGETS = [
    {"setup": "pursuiter", "distance_m": 4000, "time_s": 255, "standing": True},
    {"setup": "pursuiter", "distance_m": 3000, "time_s": 210, "standing": True, "start_power_ratio": 1.5},
    {"setup": "sprinter", "distance_m": 200, "time_s": 11.2, "standing": False},
    {"setup": "junior", "distance_m": 2000, "time_s": 150, "standing": True},
    {"setup": "junior", "distance_m": 250, "time_s": 2, "standing": True},
]
GEARS = [(52, 14, 2.10, 110, 15), (49, 15, 2.096, 95, 12.5), (60, 15, 2.13, 130, 19)]


def _options(case: dict) -> dict:
    return {key: case[key] for key in ("standing", "split_every_m", "start_power_ratio", "start_force_n") if key in case}


def build_vectors() -> dict:
    return {
        "_comment": "Generated by backend/tests/physics_vectors.py — do not edit by hand.",
        "constants": {
            "G": physics.G,
            "DEFAULT_CRR": physics.DEFAULT_CRR,
            "DEFAULT_EFFICIENCY": physics.DEFAULT_EFFICIENCY,
            "DEFAULT_ROTATING_MASS_KG": physics.DEFAULT_ROTATING_MASS_KG,
            "DEFAULT_START_POWER_RATIO": physics.DEFAULT_START_POWER_RATIO,
            "DEFAULT_START_FORCE_N": physics.DEFAULT_START_FORCE_N,
            "SIMULATION_STEP_S": physics.SIMULATION_STEP_S,
        },
        "setups": {name: asdict(setup) for name, setup in SETUPS.items()},
        "air_density": [
            {
                **case,
                "expected": physics.air_density(
                    case["temp_c"],
                    pressure_pa=case["pressure_pa"],
                    elevation_m=case["elevation_m"],
                    humidity_pct=case["humidity_pct"],
                ),
            }
            for case in AIR
        ],
        "power_required": [
            {
                "setup": name,
                "speed_ms": v,
                "accel_ms2": a,
                "expected": physics.power_required_w(v, SETUPS[name], a),
            }
            for name, v, a in SPEEDS
        ],
        "steady_speed": [
            {"setup": name, "power_w": p, "expected": physics.steady_speed_ms(p, SETUPS[name])} for name, p in POWERS
        ],
        "simulate": [
            {
                **case,
                "expected": asdict(
                    physics.simulate(case["distance_m"], case["power_w"], SETUPS[case["setup"]], **_options(case))
                ),
            }
            for case in SIMULATIONS
        ],
        "power_for_time": [
            {
                **case,
                "expected": physics.power_for_time_w(
                    case["distance_m"], case["time_s"], SETUPS[case["setup"]], **_options(case)
                ),
            }
            for case in TARGETS
        ],
        "gearing": [
            {
                "chainring": chainring,
                "cog": cog,
                "rollout_m": rollout,
                "cadence_rpm": cadence,
                "speed_ms": speed,
                "expected": {
                    "development_m": physics.development_m(chainring, cog, rollout),
                    "gear_inches": physics.gear_inches(chainring, cog, rollout),
                    "speed_ms": physics.speed_from_cadence_ms(cadence, chainring, cog, rollout),
                    "cadence_rpm": physics.cadence_from_speed_rpm(speed, chainring, cog, rollout),
                },
            }
            for chainring, cog, rollout, cadence, speed in GEARS
        ],
    }


if __name__ == "__main__":
    VECTORS_PATH.write_text(json.dumps(build_vectors(), indent=2) + "\n")
    print(f"wrote {VECTORS_PATH}")
